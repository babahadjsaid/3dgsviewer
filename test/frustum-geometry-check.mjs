import assert from 'node:assert/strict';
import * as pc from 'playcanvas/build/playcanvas.mjs';
import {createCameraFrustums} from '../dist/features/camera-frustums.js';
const canvas={width:64,height:64,addEventListener(){},removeEventListener(){},getBoundingClientRect(){return {left:0,top:0,width:64,height:64}}};
const device=new pc.NullGraphicsDevice(canvas);
const app=new pc.AppBase(canvas);
const opts=new pc.AppOptions();
opts.graphicsDevice=device;
opts.componentSystems=[pc.RenderComponentSystem];
opts.resourceHandlers=[];
app.init(opts);
let receive, unsubscribed=false;
const feature=createCameraFrustums({subscription:{topic:'job',service:{on:(_,fn)=>{receive=fn;return ()=>{unsubscribed=true}}}}});
const scene={app,drawLine(){throw Error('must use scene mesh')}};
feature.setup(scene);
feature.sceneReady(scene);
const event={event:'gs_cameras',data:{poses:[[[0,-1,0,2],[1,0,0,-1],[0,0,1,-3],[0,0,0,1]]],intrs:[[[500,0,320],[0,500,240],[0,0,1]]]}};
receive(event);
let root=app.root.findByName('Training camera frustums');
assert.ok(root?.render);
const instance=root.render.meshInstances[0];
assert.equal(instance.material.depthTest,true);
assert.equal(instance.material.depthWrite,true);
assert.equal(instance.material.blendType,pc.BLEND_NONE);
assert.equal(instance.mesh.primitive[0].type,pc.PRIMITIVE_LINES);
const positions=[];instance.mesh.getPositions(positions);
assert.deepEqual(positions.slice(0,3),[1,2,3]);
feature.frame(0,scene);
receive(event);
assert.notEqual(app.root.findByName('Training camera frustums'),root);
receive({event:'gs_cameras',data:{poses:[],intrs:[]}});
assert.equal(app.root.findByName('Training camera frustums'),null);
receive(event);
feature.teardown(scene);
assert.equal(app.root.findByName('Training camera frustums'),null);
assert.equal(unsubscribed,true);
app.destroy();
console.log('Real PlayCanvas geometry, opaque depth material, replacement, empty update and teardown passed');
